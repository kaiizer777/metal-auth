/// Returns `true` if `password` appears in the common password blocklist.
///
/// Comparison is case-insensitive (normalizes input to lowercase before binary search).
/// Per spec: filtering is done here, not at the call site.
pub fn is_common_password(password: &str) -> bool {
    if password.chars().any(char::is_uppercase) {
        let pw_lower = password.to_lowercase();
        BLOCKLIST.binary_search(&pw_lower.as_str()).is_ok()
    } else {
        BLOCKLIST.binary_search(&password).is_ok()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_common_passwords_are_blocked() {
        assert!(is_common_password("password"));
        assert!(is_common_password("12345678"));
        assert!(is_common_password("qwerty123"));
        assert!(is_common_password("iloveyou"));
        assert!(is_common_password("sunshine"));
        assert!(is_common_password("football"));
        assert!(is_common_password("baseball"));
    }

    #[test]
    fn case_insensitivity_enforced() {
        assert!(is_common_password("PASSWORD"));
        assert!(is_common_password("Password"));
        assert!(is_common_password("PaSsWoRd"));
        assert!(is_common_password("QWERTY123"));
        assert!(is_common_password("Football"));
        assert!(is_common_password("BASEBALL"));
    }

    #[test]
    fn uncommon_passwords_pass_blocklist() {
        assert!(!is_common_password("Tr0ub4dor&3"));
        assert!(!is_common_password("correct-horse-battery-staple"));
        assert!(!is_common_password("xkRt9!mWqP2#vLsN"));
        assert!(!is_common_password("🔐🔑🗝️🔒🔓🛡️⚔️🏰"));
    }

    #[test]
    fn blocklist_entries_are_all_at_least_8_code_points() {
        for entry in BLOCKLIST {
            let count = entry.chars().count();
            assert!(
                count >= 8,
                "blocklist entry {:?} has {} code points (must be >= 8)",
                entry,
                count
            );
        }
    }

    #[test]
    fn blocklist_is_strictly_sorted_and_deduplicated() {
        for window in BLOCKLIST.windows(2) {
            assert!(
                window[0] < window[1],
                "blocklist not strictly sorted or has duplicate: {:?} vs {:?}",
                window[0],
                window[1]
            );
        }
    }

    #[test]
    fn blocklist_has_at_least_500_entries() {
        assert!(
            BLOCKLIST.len() >= 500,
            "blocklist too small: {}",
            BLOCKLIST.len()
        );
    }
}
